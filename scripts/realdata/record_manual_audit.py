def main():
    source = Path("data/real/real-v1/audit-input.json")
    records = json.loads(source.read_text(encoding="utf8"))
    manifest = Path("src/omnistream/eval/real/real-v1-manifest.jsonl")
    items = []
    for row in records:
        index = row["index"]
        invalid = INVALID.get(index, [])
        assert set(invalid) <= set(row["predicted"]), (index, invalid, row["predicted"])
        items.append(
            {
                "id": row["id"],
                "index": index,
                "source": row["source"],
                "predicted_names": row["predicted"],
                "valid_predictions": [p for p in row["predicted"] if p not in invalid],
                "invalid_predictions": invalid,
                "missed_name_examples": MISSED.get(index, []),
                "quality_note": NOTES[index],
            }
        )
    predicted = sum(len(r["predicted_names"]) for r in items)
    valid = sum(len(r["valid_predictions"]) for r in items)
    result = {
        "status": "completed manual spot-check",
        "reviewer": "implementation agent, direct reading; no LLM extraction/judge calls",
        "seed": 20261113,
        "manifest_sha256": hashlib.sha256(manifest.read_bytes()).hexdigest(),
        "items_reviewed": len(items),
        "scope": "First 1100 clean-text characters of each fixed-seed sample item; complete text for shorter summaries. Full-document predicted names restricted to whole-name presence in that prefix. Titles excluded from entity scoring. Validity requires an organisation, person or product referent in context; partial names and aliases counted as valid when unambiguous, duplicates not penalised. Missed-name examples are qualitative, not exhaustive; no recall claim. This is not a held-out NER benchmark.",
        "predicted_names_reviewed": predicted,
        "valid_prediction_names": valid,
        "invalid_prediction_names": predicted - valid,
        "name_precision": valid / predicted,
        "items_with_missed_name_examples": sum(
            bool(r["missed_name_examples"]) for r in items
        ),
        "conclusion": "Organisation anchors are useful, but product recall, alias fragmentation and cover-page/legal boilerplate errors prevent treating raw overlap counts as gold entity-linking labels. Manually validate entities used for future questions.",
        "items": items,
    }
    Path("src/omnistream/eval/real/real-v1-ner-audit.json").write_text(
        json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf8"
    )
    print(json.dumps({k: v for k, v in result.items() if k != "items"}, indent=2))


if __name__ == "__main__":
    main()
